def read_energy(outcar: str) -> Optional[float]:
    """读取 OUTCAR 末步自由能 (eV)."""
    if not os.path.exists(outcar):
        return None
    vals = []
    with open(outcar) as f:
        for line in f:
            if "free  energy" in line:
                m = re.search(r"free  energy\s*=\s*([-\d.]+)", line)
                if m:
                    vals.append(float(m.group(1)))
    return vals[-1] if vals else None


def read_max_force(outcar: str) -> Optional[float]:
    """读取 OUTCAR 末步 TOTAL-FORCE 最大力分量 (eV/Ang)."""
    if not os.path.exists(outcar):
        return None
    blocks = []
    current = []
    with open(outcar) as f:
        for line in f:
            if "TOTAL-FORCE" in line:
                if current:
                    blocks.append(current)
                current = []
            elif current is not None:
                m = re.match(r"\s*([-\d.]+)\s+([-\d.]+)\s+([-\d.]+)\s+([-\d.]+)\s+([-\d.]+)\s+([-\d.]+)", line)
                if m:
                    current.append([float(x) for x in m.groups()])
    if not blocks:
        return None
    last = blocks[-1]
    if not last:
        return None
    return max(abs(row[3]) for row in last)


def is_converged(outcar: str) -> bool:
    """检查 OUTCAR 是否达到电子步收敛."""
    if not os.path.exists(outcar):
        return False
    with open(outcar) as f:
        for line in f:
            if "reached required accuracy" in line:
                return True
    return False


def is_failed(outcar: str) -> bool:
    if not os.path.exists(outcar):
        return False
    with open(outcar) as f:
        for line in f:
            if "aborting loop" in line or "Error" in line and "ERROR" in line.upper():
                return True
    return False


