def extract_atomic_spin_from_vasprun(vasprun_xml: str) -> dict:
    """
    从 vasprun.xml 提取逐原子磁矩（自旋密度近似）。
    返回 {species: [spin, spin, ...]}。需 VASP 计算含 ISPIN=2。
    """
    import xml.etree.ElementTree as ET

    tree = ET.parse(vasprun_xml)
    root = tree.getroot()
    atoms = root.find("atominfo/atoms")
    n_atoms = int(atoms.text.strip())
    species = [s.text.strip() for s in root.find("atominfo/array[@name='atomtypes']").find("set")][::5]
    # 解析 magnetization 数组（最后一条）
    mag_nodes = root.findall("calculation")
    mag = None
    for calc in mag_nodes:
        node = calc.find("eigenvalues")
        node2 = calc.find("partial")
        _ = (node, node2)
    # 简化实现：从 final ionic step 的 /calculation/array name=magnetization
    final_calc = mag_nodes[-1]
    mag_arrays = final_calc.find("array[@name='magnetization']/set/r")
    if mag_arrays is None:
        return {}
    spins = []
    for row in list(mag_arrays)[-n_atoms:]:
        spins.append(float(row.text.split()[-1]))
    return {"species_order": species, "spins": spins}
